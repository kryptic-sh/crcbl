#[cfg(test)]
mod tests {
    use super::*;

    use crcbl::reflect::{Kind, Range, Value, get_path, set_path};
    use crcbl::scene::scn::{Env, EnvCamera, IdMap};

    use crate::game::{BRICK_COUNT, BRICK_HEIGHT, BRICK_WIDTH, brick_position};

    /// The environment the committed `env.ron` holds.
    ///
    /// The camera is where `crate::audio` puts the mixer's listener — back
    /// [`crate::audio::LISTENER_STANDOFF`] from the play plane, aimed at the
    /// middle of the field — because there is one camera in this game and the
    /// listener is at it. The ambient is [`crate::art::SURROUND`], the linear
    /// clear the court sits in, which is the only light breakout has: its
    /// sprites are unlit, so nothing else could fill this in truthfully.
    ///
    /// Both are read from the constants rather than retyped, so a change to
    /// either is a red test here rather than a file that quietly disagrees with
    /// the game.
    ///
    /// Neither reaches the renderer yet — the orthographic camera's extent is
    /// derived from the surface's aspect in `crate::gpu::camera_half_width`,
    /// and the clear is `art::SURROUND` directly. `env.ron` is a file the
    /// format requires and this test is what keeps its numbers from drifting
    /// away from the two constants they were taken from.
    fn env() -> Env {
        Env {
            camera: EnvCamera {
                position: [0.0, 0.0, -crate::audio::LISTENER_STANDOFF],
                look_at: [0.0, 0.0, 0.0],
            },
            ambient: [
                crate::art::SURROUND[0],
                crate::art::SURROUND[1],
                crate::art::SURROUND[2],
            ],
        }
    }

    /// The board `game::brick_position` describes, in a world of its own, ready
    /// to be written out.
    ///
    /// The Z half-extent is the one number here with no constant behind it: the
    /// field is flat, so a brick's depth only has to be enough for a sphere
    /// swept at `z = 0` to hit it, and it is the same `0.5` the grid was always
    /// spawned with.
    fn generated() -> (Scene, IdMap, World) {
        let mut world = World::new();
        world.register_system(Box::new(System::<Brick>::new(BRICKS)));
        let mut ids = IdMap::new();
        let mut rows = Vec::with_capacity(BRICK_COUNT);
        for index in 0..BRICK_COUNT {
            let entity = world.spawn();
            ids.assign(entity);
            rows.push((
                entity,
                Brick {
                    position: brick_position(index).to_array(),
                    half_extents: [BRICK_WIDTH / 2.0, BRICK_HEIGHT / 2.0, 0.5],
                },
            ));
        }
        let system = world
            .system_mut::<System<Brick>>()
            .expect("just registered");
        for (entity, brick) in rows {
            system.attach(entity, brick);
        }
        let scene = Scene::new("board", vec![BRICKS.to_string()], env());
        (scene, ids, world)
    }

    /// Asserts a committed file is what the writer wrote, and says *where* it
    /// stopped agreeing when it is not.
    ///
    /// Line by line rather than as two strings: a chunk file is one row per
    /// brick, and an `assert_eq!` over the pair prints both in full for one
    /// changed coordinate.
    ///
    /// Byte for byte, on every platform: `.gitattributes` pins `*.ron` to LF,
    /// so a Windows checkout hands `include_str!` the bytes the repository
    /// holds and nothing here has to fold a CRLF the transport might have
    /// added.
    fn assert_committed(key: &str, written: &str, committed: &str) {
        if written == committed {
            return;
        }
        match written
            .lines()
            .zip(committed.lines())
            .position(|(written, committed)| written != committed)
        {
            Some(line) => panic!(
                "{key} line {}: the writer writes `{}`, the file has `{}`",
                line + 1,
                written.lines().nth(line).expect("the line just compared"),
                committed.lines().nth(line).expect("the line just compared"),
            ),
            None => panic!(
                "{key}: the writer writes {} lines, the file has {}",
                written.lines().count(),
                committed.lines().count(),
            ),
        }
    }

    /// **The committed board is exactly what the writer writes** from
    /// `game::brick_position`, which is what lets the layout live in a
    /// file without a second copy of it in code.
    ///
    /// Generated once by [`Scene::save`] and maintained that way: ron prints a
    /// float through Rust's shortest-round-trip `Display`, which round-trips a
    /// *parsed* value and not a typed one, so a hand-edited coordinate is a
    /// failure here rather than a board that quietly moved.
    #[test]
    fn the_committed_board_is_what_the_writer_writes() {
        let (scene, ids, mut world) = generated();
        // This game's own registration rather than a second list, so the writer
        // test is about the vocabulary the game ships.
        let mut registry = Registry::new();
        register_components(&mut registry);
        let files = scene
            .save(&mut world, &ids, &registry.codecs())
            .expect("a generated board is writable");

        assert_committed("scene.ron", &files["scene.ron"], BOARD_SCENE_RON);
        assert_committed("env.ron", &files["env.ron"], BOARD_ENV_RON);
        assert_committed("sys/bricks.ron", &files["sys/bricks.ron"], BOARD_BRICKS_RON);
        assert_eq!(
            files.keys().collect::<Vec<_>>(),
            ["env.ron", "scene.ron", "sys/bricks.ron"],
            "the manifest's files and nothing else"
        );
        for (key, text) in &files {
            assert!(!text.contains('\r'), "the newline is pinned in {key}");
        }
    }

    /// The other half of the same claim: what the committed files *parse* to is
    /// the grid the game used to build in code. A writer that agreed with
    /// itself while dropping a field would pass the byte comparison above.
    #[test]
    fn the_committed_board_parses_to_the_grid_the_code_generates() {
        let board = Board::built_in();
        assert_eq!(board.bricks().len(), BRICK_COUNT);
        for (index, brick) in board.bricks().iter().enumerate() {
            assert_eq!(
                brick.position(),
                brick_position(index),
                "brick {index} moved"
            );
            assert_eq!(
                brick.half_extents(),
                DVec3::new(BRICK_WIDTH / 2.0, BRICK_HEIGHT / 2.0, 0.5),
                "brick {index} changed size"
            );
        }
    }

    /// A directory with no `scene.ron` is refused by the key that is missing,
    /// and the key is spelled the way `--scene` points at it — the scene
    /// directory *is* the root, so the header is `scene.ron` and not
    /// `board.scn/scene.ron`. A loader looking under the built-in name would
    /// report a file the caller never named.
    #[test]
    fn a_directory_with_no_header_is_refused_by_the_missing_key() {
        let dir = std::env::temp_dir().join(format!("breakout-empty-{}.scn", std::process::id()));
        std::fs::create_dir_all(&dir).expect("the temp dir is writable");
        let message = Board::read_dir(dir.to_str().expect("utf-8"))
            .expect_err("a directory with no scene.ron is not a board");
        assert!(message.contains("scene.ron"), "{message}");
        assert!(message.contains("path not found"), "{message}");
        assert!(
            !message.contains(BOARD),
            "the key must be the caller's, not the built-in board's: {message}"
        );
    }

    /// A directory whose header is not RON is refused by line and column, so a
    /// person fixing it is told where to look.
    #[test]
    fn a_header_that_is_not_ron_is_refused_by_line_and_column() {
        let dir = std::env::temp_dir().join(format!("breakout-bad-{}.scn", std::process::id()));
        std::fs::create_dir_all(&dir).expect("the temp dir is writable");
        std::fs::write(
            dir.join("scene.ron"),
            "Scene(\n    format: 0,\n    nome: \"board\",\n)",
        )
        .expect("the temp dir is writable");
        let message = Board::read_dir(dir.to_str().expect("utf-8"))
            .expect_err("a header that is not a scene is not a board");
        assert!(message.contains("scene.ron"), "{message}");
        assert!(message.contains("line"), "{message}");
        assert!(message.contains("column"), "{message}");
    }

    // -- reflection ----------------------------------------------------------

    #[test]
    fn a_brick_describes_the_two_rows_a_property_panel_draws() {
        let brick = Brick {
            position: [1.0, 2.0, 3.0],
            half_extents: [BRICK_WIDTH / 2.0, BRICK_HEIGHT / 2.0, 0.5],
        };

        assert_eq!(crcbl::reflect::Reflect::type_name(&brick), "Brick");
        assert_eq!(crcbl::reflect::Reflect::kind(&brick), Kind::Struct);

        let rows = crcbl::reflect::Reflect::fields(&brick);
        assert_eq!(
            rows.iter().map(|row| row.label).collect::<Vec<_>>(),
            ["Position", "Half extents"]
        );
        assert_eq!(rows[0].range, None, "a centre may be anywhere on the board");
        assert_eq!(
            rows[1].range,
            Some(Range {
                min: 0.0,
                max: 28.0
            }),
            "a half extent is never negative and never wider than the playfield"
        );
    }

    #[test]
    fn an_edit_to_a_brick_reads_back_and_undoes() {
        let mut brick = Brick {
            position: [1.0, 2.0, 3.0],
            half_extents: [1.2, 0.4, 0.5],
        };
        let before = brick;

        let old = get_path(&brick, "position.0").expect("the row is an f64");
        assert_eq!(old, Value::Float(1.0));
        set_path(&mut brick, "position.0", &Value::Float(-6.5)).expect("an f64 takes a float");
        assert_eq!(brick.position(), DVec3::new(-6.5, 2.0, 3.0));

        set_path(&mut brick, "position.0", &old).expect("the recorded value");
        assert_eq!(brick, before);
    }
}
